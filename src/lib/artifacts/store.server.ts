import { EXT_META, sanitizeFilename, type ArtifactMeta } from "./spec";

export const MAX_ARTIFACT_BYTES = 25 * 1024 * 1024;

export type StoreContext = {
  /** Authenticated user id, or null for guest sessions. */
  userId: string | null;
  threadId: string | null;
};

/** Magic-byte checks so we never hand back a corrupt file. */
function validateBytes(bytes: Uint8Array, ext: string): string | null {
  if (bytes.byteLength === 0) return "generated file is empty";
  if (bytes.byteLength > MAX_ARTIFACT_BYTES) return "generated file exceeds the 25MB limit";
  const head = Array.from(bytes.slice(0, 4));
  const isZip = head[0] === 0x50 && head[1] === 0x4b;
  if (["docx", "xlsx", "pptx", "ods", "zip"].includes(ext) && !isZip) {
    return "generated container is not a valid package";
  }
  if (ext === "pdf") {
    const sig = new TextDecoder().decode(bytes.slice(0, 5));
    if (sig !== "%PDF-") return "generated PDF header is invalid";
  }
  if (ext === "png" && !(head[0] === 0x89 && head[1] === 0x50)) {
    return "generated PNG header is invalid";
  }
  return null;
}

/**
 * Validate → upload to the private `artifacts` bucket → record metadata →
 * hand back a short-lived signed URL. Filesystem/storage paths never leak.
 */
export async function storeArtifact(
  ctx: StoreContext,
  input: { filename: string; ext: string; bytes: Uint8Array },
): Promise<ArtifactMeta> {
  const ext = input.ext.toLowerCase();
  const meta = EXT_META[ext] ?? { mime: "application/octet-stream", kind: "File" };
  const filename = sanitizeFilename(input.filename, ext);

  const problem = validateBytes(input.bytes, ext);
  if (problem) throw new Error(`Validation failed: ${problem}`);

  const { supabaseAdmin } = await import("@/integrations/supabase/client.server");

  const id = crypto.randomUUID();
  const owner = ctx.userId ?? "guest";
  const path = `${owner}/${ctx.threadId ?? "adhoc"}/${id}/${filename}`;

  const { error: upErr } = await supabaseAdmin.storage
    .from("artifacts")
    .upload(path, input.bytes, { contentType: meta.mime, upsert: false });
  if (upErr) throw new Error(`Storage failed: ${upErr.message}`);

  // Read-back check: the object must exist and be non-empty.
  const { data: dl, error: dlErr } = await supabaseAdmin.storage.from("artifacts").download(path);
  if (dlErr || !dl || dl.size === 0) throw new Error("Validation failed: stored file unreadable");

  if (ctx.userId) {
    await supabaseAdmin.from("artifacts").insert({
      id,
      user_id: ctx.userId,
      thread_id: ctx.threadId,
      filename,
      mime_type: meta.mime,
      extension: ext,
      kind: meta.kind,
      size_bytes: input.bytes.byteLength,
      storage_path: path,
    });
  }

  const { data: signed, error: signErr } = await supabaseAdmin.storage
    .from("artifacts")
    .createSignedUrl(path, 60 * 60 * 24 * 7, { download: filename });
  if (signErr || !signed?.signedUrl) throw new Error("Storage failed: could not sign download URL");

  return {
    id,
    filename,
    mimeType: meta.mime,
    extension: ext,
    kind: meta.kind,
    sizeBytes: input.bytes.byteLength,
    url: signed.signedUrl,
    status: "ready",
  };
}

/** Fetch previously generated bytes (used by the ZIP tool). */
export async function loadArtifactBytes(
  ctx: StoreContext,
  id: string,
): Promise<{ filename: string; bytes: Uint8Array } | null> {
  const { supabaseAdmin } = await import("@/integrations/supabase/client.server");
  const owner = ctx.userId ?? "guest";
  const { data: list } = await supabaseAdmin.storage
    .from("artifacts")
    .list(`${owner}/${ctx.threadId ?? "adhoc"}/${id}`);
  const entry = list?.[0];
  if (!entry) return null;
  const path = `${owner}/${ctx.threadId ?? "adhoc"}/${id}/${entry.name}`;
  const { data, error } = await supabaseAdmin.storage.from("artifacts").download(path);
  if (error || !data) return null;
  return { filename: entry.name, bytes: new Uint8Array(await data.arrayBuffer()) };
}
